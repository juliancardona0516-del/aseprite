// Rebuilds assets/sprites.js from Pixelbolt sources, so the spike uses real Pixelbolt output as textures.
//   node build-assets.cjs
// Pixelbolt CLI: $PIXELBOLT if set (e.g. "node /path/to/Pixelbolt/bin/pixelbolt.js"), else "npx -y pixelbolt@0.14.0".
// Sources: assets-src/knight.poses.json (the knight from the hero rig) and the skill's examples/quality/shale.json (a rock).
// Output is a classic script (window.PIXELBOLT_SPRITES = {...}) with data-URI PNGs: it loads from file:// too.
const { execSync } = require('child_process'), fs = require('fs'), path = require('path');
const here = __dirname, cache = path.join(here, '.cache', 'pixelbolt'), cli = process.env.PIXELBOLT || 'npx -y pixelbolt@0.14.0';
const examples = path.join(here, '..', '..', '.claude', 'skills', 'pixelbolt-pixel-art', 'examples');
const run = cmd => JSON.parse(execSync(cmd, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }));
fs.rmSync(cache, { recursive: true, force: true }); fs.mkdirSync(cache, { recursive: true });
const jobs = [
  { name: 'knight', recipe: path.join(cache, 'knight.json'), compile: path.join(here, 'assets-src', 'knight.poses.json'), frames: ['stand', 'idle-rest', 'idle-inhale', 'idle-exhale', 'idle-settle'] },
  { name: 'rock', recipe: path.join(examples, 'quality', 'shale.json'), frames: null },
];
const out = {};
for (const j of jobs) {
  if (j.compile) run(`${cli} compile "${j.compile}" --out "${j.recipe}"`);
  const dir = path.join(cache, j.name), r = run(`${cli} render "${j.recipe}" --out "${dir}"`);
  if (!r.ok) throw new Error(`pixelbolt render failed for ${j.name}`);
  const atlasFile = fs.readdirSync(dir).find(f => f.endsWith('.atlas.json')), atlas = JSON.parse(fs.readFileSync(path.join(dir, atlasFile), 'utf8'));
  const names = j.frames || Object.keys(atlas.frames).slice(0, 1);
  out[j.name] = names.map(n => {
    const f = atlas.frames[n], file = path.join(dir, 'frames', `${n}.png`), png = fs.readFileSync(fs.existsSync(file) ? file : path.join(dir, 'frames', fs.readdirSync(path.join(dir, 'frames'))[0]));
    fs.writeFileSync(path.join(here, 'assets', `${j.name}-${n}.png`), png);
    return { name: n, w: f.sourceSize.w, h: f.sourceSize.h, ms: f.duration || 200, anchor: f.anchorPx || { x: Math.floor(f.sourceSize.w / 2), y: f.sourceSize.h - 1 }, src: 'data:image/png;base64,' + png.toString('base64') };
  });
}
fs.writeFileSync(path.join(here, 'assets', 'sprites.js'),
  '// Generated by build-assets.cjs from Pixelbolt 0.14.0 output. Do not edit by hand.\nwindow.PIXELBOLT_SPRITES = ' + JSON.stringify(out) + ';\n');
console.log(Object.entries(out).map(([k, v]) => `${k}: ${v.length} frame(s) ${v[0].w}x${v[0].h}`).join(', '));
